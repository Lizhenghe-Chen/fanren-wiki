/* ---------------- 飞行更新（按阶段时间表 + 相机呼吸） ---------------- */
var stageZoom=.5;
function flyUpdate(dt){
  if(state!=="fly") return;
  t+=dt*speed/STAGE_DUR[stageIdx];
  if(t>1) t=1;
  var pts=STAGE_PATHS[stageIdx], tm=STAGE_TIME[stageIdx];
  var el=t*STAGE_DUR[stageIdx];
  /* 时间 → 位置：在累计时间表上二分，段内线性插值 */
  var lo=0, hi=tm.length-1;
  while(hi-lo>1){ var mid=(lo+hi)>>1; if(tm[mid]<=el) lo=mid; else hi=mid; }
  var span=tm[hi]-tm[lo], f=span>1e-6?clamp((el-tm[lo])/span,0,1):0;
  var idx=lo;
  hero={x:pts[lo].x+(pts[hi].x-pts[lo].x)*f, y:pts[lo].y+(pts[hi].y-pts[lo].y)*f};
  heroIdx=lo;
  heroWarp=0; heroWarpP=0;
  var wl0=STAGE_WARPS[stageIdx]||[], curW=null;
  for(var q=0;q<wl0.length;q++) if(idx>=wl0[q].start&&idx<wl0[q].end){ heroWarp=1; curW=wl0[q]; }
  var zz=stageZoom*(1+.08*Math.sin(Math.PI*t));
  if(heroWarp&&curW){
    /* 传送中：镜头不再追着一个高速点跑（那才是「一跳而过」的来源），
     * 而是直接朝目的地推进并稍微拉远 —— 读起来是「换了个地方」而不是「快进」 */
    heroWarpP=clamp((idx-curW.start)/Math.max(1,curW.end-curW.start),0,1);
    camTarget(curW.to.x,curW.to.y,zz*(1-.34*Math.sin(Math.PI*heroWarpP)));
  }else{
    /* 相机前瞻：宽窗口切线（±6）更稳定，沿切线超前 46 单位，镜头走在光点之前 */
    var p2=pts[Math.min(pts.length-1,idx+6)], p1=pts[Math.max(0,idx-6)];
    var dx=p2.x-p1.x, dy=p2.y-p1.y, dl=Math.hypot(dx,dy)||1;
    camTarget(hero.x+dx/dl*46, hero.y+dy/dl*46, zz);
  }
  /* 移除常飞时的高频抖动，仅保留平稳巡游（portal/到达事件另行 shake） */
  spawnTrail(hero.x,hero.y,heroWarp?4:(Math.random()<.5?1:2));
  /* 传送段两端各来一次：起点「穿走」、终点「抵达」，中途不再叠特效 */
  var wlist=STAGE_WARPS[stageIdx]||[];
  for(var wi=0;wi<wlist.length;wi++){
    var wb=wlist[wi];
    if(!warpFired[wi] && idx>=wb.start){
      warpFired[wi]=1;
      var wp=pts[wb.start];
      spawnWarp(wp.x,wp.y); flash(.4); shake(.3);
      var tag=(STAGE_TAG[stageIdx]||[])[wi];
      if(tag) warpTag={txt:"传 送 · "+(tag.to||"").split(" · ")[0], until:now+WARP_SEC+.8};
    }
    if(!warpEndFired[wi] && idx>=wb.end){
      warpEndFired[wi]=1;
      spawnWarp(wb.to.x,wb.to.y); flash(.22);
    }
  }
  /* 到站判定直接比时间（与位置同一张时间表），末站也不会漏 */
  var seg=STAGE_LOCS[stageIdx], npos=STAGE_NPOS[stageIdx];
  while(arriveIdx<seg.length && el>=tm[npos[arriveIdx]]-1e-6){
    var loc=seg[arriveIdx];
    if(!arrived[arriveIdx]){
      arrived[arriveIdx]=1;
      onArrive(loc,arriveIdx);
    }
    arriveIdx++;
  }
  /* 阶段收尾放在到站事件之后：末站同样要触发到达（含 portal 提示） */
  if(t>=1){
    if(stageIdx<NSTAGE) scheduleNext();
    else finale();
  }
}
