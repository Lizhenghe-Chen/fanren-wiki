/* 帧率无关的指数阻尼（critically damped），lambda 越大跟得越快 */
function dampTo(cur,target,lambda,dt){ return cur+(target-cur)*(1-Math.exp(-lambda*dt)); }
function camSmooth(dt){
  /* 传送中加快阻尼：镜头要在一两个身位内跟上，否则光点会被甩出画面；
   * 暂停时进一步加速收敛，让镜头几百毫秒内停稳（否则按了暂停还会缓慢漂移几像素） */
  var kr=(heroWarp?2.6:1)*((MODE==="play"&&!playing)?4:1);
  /* 目标层：快速阻尼，吃掉跟踪点/前瞻切线的跳变 */
  cam.lx=dampTo(cam.lx,cam.tx,9*kr,dt);
  cam.ly=dampTo(cam.ly,cam.ty,9*kr,dt);
  cam.lz=dampTo(cam.lz,cam.tz,7*kr,dt);
  /* 相机层：跟随平滑目标，丝滑无抖动 */
  cam.x=dampTo(cam.x,cam.lx,5.5,dt);
  cam.y=dampTo(cam.y,cam.ly,5.5,dt);
  cam.zoom=dampTo(cam.zoom,cam.lz,5,dt);
  if(cam.flash>0) cam.flash=Math.max(0,cam.flash-dt*1.6);
  if(cam.shake>0) cam.shake=Math.max(0,cam.shake-dt*2.4);
  if(cam.sfx>0) cam.sfx=Math.max(0,cam.sfx-dt*1.4);
  if(cam.heroShake>0) cam.heroShake=Math.max(0,cam.heroShake-dt*3);
}
