/* ---------------- 分区多边形（加权 Voronoi 剖分 → 共享形变 → 陆缘裁剪） ----------------
 * 以各分区的锚点作 Voronoi 剖分，得到相互咬合、不重叠的领土块；
 * 剖分在归一化 (u,v) 圆内进行（u 向东、v 向北），再映射回世界坐标。
 */
var SUBCELL={};
function clipHalf(poly,nx,ny,c){           /* 保留 nx*x + ny*y + c <= 0 的一侧 */
  var out=[];
  for(var i=0;i<poly.length;i++){
    var a=poly[i], b=poly[(i+1)%poly.length];
    var da=nx*a.x+ny*a.y+c, db=nx*b.x+ny*b.y+c;
    if(da<=0) out.push(a);
    if((da<0&&db>0)||(da>0&&db<0)){
      var t=da/(da-db);
      out.push({x:a.x+(b.x-a.x)*t, y:a.y+(b.y-a.y)*t});
    }
  }
  return out;
}
function subAnchor(reg,sb){
  /* 锚点：核心区取陆心；显式 seed:[u,v] 直接定位（用于天南按官方舆图摆块）；
     否则取角度区间中值处的径向中点，并做确定性抖动避免共圆规整 */
  if(sb.core) return {u:0, v:0};
  if(sb.seed) return {u:sb.seed[0], v:sb.seed[1]};
  var sd=hashStr(reg.name+"|"+sb.name);
  var am=(sb.a0+sb.a1)/2 + (rnd1(sd)-.5)*(sb.a1-sb.a0)*.34;
  var rm=(sb.r0+sb.r1)/2 + (rnd1(sd+7)-.5)*.14;
  return {u:Math.cos(am)*rm, v:Math.sin(am)*rm};
}
function subCells(reg){
  if(SUBCELL[reg.name]) return SUBCELL[reg.name];
  var subs=SUBS.filter(function(s){return s.reg===reg.name;});
  var seeds=subs.map(function(sb){
    var an=subAnchor(reg,sb);
    return {sb:sb, x:reg.wx+an.u*reg.wrx, y:reg.wy-an.v*reg.wry*1.18};
  });
  var R=2.4, M=80, out=[];
  seeds.forEach(function(s,i){
    var poly=[];
    for(var m=0;m<M;m++){
      var t=m/M*6.283185;
      poly.push({x:reg.wx+Math.cos(t)*reg.wrx*R, y:reg.wy+Math.sin(t)*reg.wry*R*1.18});
    }
    for(var j=0;j<seeds.length&&poly.length>2;j++){
      if(j===i) continue;
      var q=seeds[j];
      poly=clipHalf(poly, 2*(q.x-s.x), 2*(q.y-s.y), (s.x*s.x+s.y*s.y)-(q.x*q.x+q.y*q.y));
    }
    if(poly.length<3) return;
    out.push({sb:s.sb, seed:{x:s.x,y:s.y}, pts:densify(poly,13).map(function(p){ return borderJitter(regionWarp(reg,p)); })});
  });
  SUBCELL[reg.name]=out;
  return out;
}
