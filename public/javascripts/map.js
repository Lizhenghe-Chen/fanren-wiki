var WARP_DIST=620;  // 世界距离阈值：超过则视为跨大陆/跨海「传送」
var SEA_DIST=130;   // 群岛内相邻站点的渡海阈值：超过则画弧形航线而非直线
/* 乱星海群岛范围（世界坐标），用于判断两点是否同处一片海域 */
var ARCH_BOX=(function(){
  var a=toWorld({x:995,y:548,re:"人界"}), b=toWorld({x:1450,y:890,re:"人界"});
  return {x0:a.x,y0:a.y,x1:b.x,y1:b.y};
})();
function sameSea(a,b){
  var inA=a.x>ARCH_BOX.x0&&a.x<ARCH_BOX.x1&&a.y>ARCH_BOX.y0&&a.y<ARCH_BOX.y1,
      inB=b.x>ARCH_BOX.x0&&b.x<ARCH_BOX.x1&&b.y>ARCH_BOX.y0&&b.y<ARCH_BOX.y1;
  return inA&&inB;
}
/* 弧线：a→b 之间按 lateral 偏移画一条鼓起的曲线（k 段） */
function arcPts(a,b,bow,k){
  var wl=Math.hypot(b.x-a.x,b.y-a.y)||1, out=[];
  /* i 从 0 起：i=0 即起点本身（bulge=0）。路径首段若是弧线，
   * 少了这个点就会「第一站从半途开始」，首个到站帧与站点差出上百单位 */
  for(var i=0;i<=k;i++){
    var t=i/k, bulge=Math.sin(Math.PI*t)*bow;
    out.push({x:a.x+(b.x-a.x)*t+(b.y-a.y)/wl*bulge, y:a.y+(b.y-a.y)*t-(b.x-a.x)/wl*bulge});
  }
  return out;
}
/* 节奏：路径按等弧长重采样，再按「步行/传送」各自的世界速度累计时间，
 * 于是每个点都对应一个时刻 —— 远距离阶段不会再一闪而过，近距离也不拖沓 */
var WALK_STEP=14, WARP_STEP=26;      // 重采样间距（世界单位）
var WALK_UPS=170;                    // 步行游历速度（世界单位 / 秒）
var WARP_SEC=1.7;                    // 每次传送的固定耗时（秒）：看「几下」而不是看「多远」
var WALK_BUDGET=24;                  // 单阶段步行时间上限（秒）：路太长整体加速，而不把传送也压成闪影
var STAGE_DWELL=.8;                  // 每个到达点的停留（秒）
var STAGE_DUR_MIN=8, STAGE_DUR_MAX=95;
function resample(poly,step){
  if(!poly||!poly.length) return [];
  var out=[{x:poly[0].x,y:poly[0].y}], carry=0, i;
  for(i=1;i<poly.length;i++){
    var a=poly[i-1], b=poly[i], d=Math.hypot(b.x-a.x,b.y-a.y);
    if(d<1e-9) continue;
    var u=carry;                       /* carry：上一段末尾余下的间距，跨段累积保证间距均匀 */
    while(u<d){
      if(u>0){ var f=u/d; out.push({x:a.x+(b.x-a.x)*f, y:a.y+(b.y-a.y)*f}); }
      u+=step;
    }
    carry=u-d;
  }
  /* 末点（=本段终点的站点坐标）必须保留：到站帧就靠它，不能被「间距太小」优化掉 */
  var last=poly[poly.length-1], lo=out[out.length-1];
  if(Math.hypot(last.x-lo.x,last.y-lo.y)>1e-6) out.push({x:last.x,y:last.y});
  return out;
}
/* Catmull-Rom 单跨：p1→p2（含两端），切向取相邻站点：路线平滑且严格经过站点 */
function catmullSpan(pts,k,seg){
  var p0=pts[Math.max(0,k-1)],p1=pts[k],p2=pts[k+1],p3=pts[Math.min(pts.length-1,k+2)], out=[];
  for(var j=0;j<seg;j++){
    var t=j/seg,t2=t*t,t3=t2*t;
    out.push({
      x:.5*((2*p1.x)+(-p0.x+p2.x)*t+(2*p0.x-5*p1.x+4*p2.x-p3.x)*t2+(-p0.x+3*p1.x-3*p2.x+p3.x)*t3),
      y:.5*((2*p1.y)+(-p0.y+p2.y)*t+(2*p0.y-5*p1.y+4*p2.y-p3.y)*t2+(-p0.y+3*p1.y-3*p2.y+p3.y)*t3)
    });
  }
  out.push({x:p2.x,y:p2.y});
  return out;
}
var STAGE_PATHS={}, STAGE_LOCS={}, STAGE_WARPS={}, STAGE_TIME={}, STAGE_TAG={}, STAGE_DUR={}, STAGE_NPOS={}, STAGE_HOPS={}, STAGE_SEGS={};
STAGES.slice(1).forEach(function(st){
  var steps=JOURNEY.filter(function(j){return j.s===st.id;});
  var names=steps.map(function(j){return j.n;});
  var pts=names.map(function(n){ return WPT[n]; });
  STAGE_LOCS[st.id]=names.map(function(n){ return LOC[n]; });
  /* 按相邻距离拆分：实线游历段 + 传送段（弧线，可含换乘的岛间渡海弧） */
  var full=[], chunks=[], warps=[], tags=[];
  var nodeChunk=[];    /* 每一站归属的段（nodeChunk[k] = 进入第 k 站的那一段） */
  function append(seg,kind,ups,from,to){
    if(!seg.length) return;
    var i0=full.length,k,p,q;
    for(k=0;k<seg.length;k++){
      p=seg[k];
      if(full.length){
        q=full[full.length-1];
        if(Math.hypot(p.x-q.x,p.y-q.y)<.6) continue;   /* 接缝去重 */
      }
      full.push(p);
    }
    if(full.length-i0<2){                       /* 单点段：仍要占一个点位，便于到站触发 */
      if(full.length===i0) full.push({x:seg[seg.length-1].x,y:seg[seg.length-1].y});
    }
    var len=0;
    for(k=i0+1;k<full.length;k++) len+=Math.hypot(full[k].x-full[k-1].x,full[k].y-full[k-1].y);
    chunks.push({i0:i0,i1:full.length-1,kind:kind,ups:ups,len:len,from:from,to:to});
    if(kind==="warp"){
      var le=full[full.length-1];
      warps.push({start:i0,end:full.length,to:{x:le.x,y:le.y}});
      tags.push({from:from,to:to,d:Math.round(len)});
    }
  }
  var i=0;
  while(i<pts.length){
    var j=i+1;
    while(j<pts.length){
      var dd=Math.hypot(pts[j].x-pts[j-1].x,pts[j].y-pts[j-1].y);
      if(dd>WARP_DIST||steps[j].warp) break;
      if(dd>SEA_DIST&&sameSea(pts[j-1],pts[j])) break;   /* 岛间渡海：另画弧线 */
      j++;
    }
    /* 步行段按「相邻两站」逐跨生成：每跨的末点就是该站坐标，
     * 「哪一站对应路径上的哪一帧」于是由构造保证，不再靠最近点搜索去猜 ——
     * 重访同一地点（阗天城 / 晋京 / 天渊城…）时，搜索会挑中后一次到访，整张时间表随之错位 */
    for(var nk=i;nk<j-1;nk++){
      var sp=resample(catmullSpan(pts,nk,30),WALK_STEP);
      if(full.length>0&&sp.length>1) sp=sp.slice(1);
      append(sp,"walk",WALK_UPS, names[nk], names[nk+1]);
      nodeChunk[nk+1]=chunks.length-1;
    }
    if(j<pts.length){
      var a=pts[j-1],b=pts[j], wl=Math.hypot(b.x-a.x,b.y-a.y)||1;
      /* 传送判定：数据里标注的（跨界/跨界面的关键行程）或距离超阈值的跨海跨陆段 */
      var isWarp=steps[j].warp||(wl>WARP_DIST&&!sameSea(a,b));
      var arc=arcPts(a,b,isWarp?wl*.14:Math.min(64,wl*.18),isWarp?10:16);
      if(full.length) arc=arc.slice(1);
      append(resample(arc,isWarp?WARP_STEP:WALK_STEP), isWarp?"warp":"sea", WALK_UPS, names[j-1], names[j]);
      nodeChunk[j]=chunks.length-1;                          /* 弧线段的终点就是这一站 */
    }
    i=j;
  }
  /* 到达点在路径上的下标：到站触发、停留与「从此处播放」共用。
   * 首站是路径起点，其余各站就是「进入它的那一段」的末点 —— 精确，无需搜索。 */
  var npos=[], q;
  for(q=0;q<names.length;q++){
    var ch0=q>0?chunks[nodeChunk[q]]:null;
    npos.push(ch0?ch0.i1:0);
    if(q>0&&npos[q]<=npos[q-1]) npos[q]=Math.min(full.length-1,npos[q-1]+1);   /* 保险：严格递增 */
  }
  /* 路程时间：步行段按世界速度累计并整体受 WALK_BUDGET 约束；
   * 传送段每次固定 WARP_SEC —— 传送的观感取决于「几次」而不是「多远」，
   * 否则跨大陆的传送会把整段路程拉长，再被总时长钳制压成一闪而过。 */
  var walkRaw=0, c, k;
  for(c=0;c<chunks.length;c++) if(chunks[c].kind!=="warp") walkRaw+=chunks[c].len/chunks[c].ups;
  var walkScale=walkRaw>WALK_BUDGET?WALK_BUDGET/walkRaw:1;
  for(c=0;c<chunks.length;c++){
    var ck=chunks[c];
    ck.sec=ck.kind==="warp"?WARP_SEC:(ck.len>0?ck.len/ck.ups*walkScale:0);
  }
  var times=[], acc=0, walkLen=0, warpLen=0;
  for(c=0;c<chunks.length;c++){
    var ch=chunks[c];
    if(ch.kind==="warp") warpLen+=ch.len; else walkLen+=ch.len;
    var part=0, dl=0;
    for(k=ch.i0;k<=ch.i1;k++){
      if(k>ch.i0){
        dl=Math.hypot(full[k].x-full[k-1].x,full[k].y-full[k-1].y);
        if(ch.len>0) acc+=dl/ch.len*ch.sec;
      }
      times[k]=acc;
    }
  }
  var travel=times.length?times[times.length-1]:0;
  /* 每个到达点复制一份点位当「停留帧」：到站时原地停顿，而不是把下一段路拖成慢动作 */
  var at={}, before=[], dup=0, path=[], tms=[], extra=0;
  npos.forEach(function(v){ at[v]=1; });
  /* before[k] 必须在下标推进过程中累计：原先先跑一遍 `before[k]=dup`（那时 dup 还是 0），
   * 于是下面两处 v+before[v] 全是恒等映射，停留帧一插就把后续下标整体推后 —— 到站时刻、
   * 传送段范围、光点淡出全部错位（越到后半段偏得越多，观感就是「一路疾驰」）。 */
  for(k=0;k<full.length;k++){
    before[k]=dup;
    times[k]+=extra;
    path.push({x:full[k].x,y:full[k].y}); tms.push(times[k]);
    if(at[k]&&k<full.length-1){
      path.push({x:full[k].x,y:full[k].y}); tms.push(times[k]+STAGE_DWELL);
      extra+=STAGE_DWELL; dup++;
    }
  }
  npos=npos.map(function(v){ return v+before[v]; });
  /* 同一批停留帧也要作用在传送段上：end 取「目的地那一帧的后一位」，
   * 于是停留时不再算作传送中（光点恢复常态），而轨迹分段仍严丝合缝 */
  warps.forEach(function(w){
    var e=Math.min(w.end,full.length)-1;   /* 传送段末点（即目的地） */
    w.start=w.start+before[w.start];
    w.end=e+before[e]+1;
  });
  /* 段的起止下标同样要换算到「插入停留帧之后」的坐标系：
   * 不换算的话，站点下标（已换算）与段范围（未换算）在对数上会越差越远，
   * 段性质判定、传送段的起止都会漂移 */
  chunks.forEach(function(c){
    var e1=Math.min(c.i1,full.length-1);
    c.i0=c.i0+before[c.i0];
    c.i1=e1+before[e1]+(at[e1]&&e1<full.length-1?1:0);
  });
  /* 总时长 = 路程 + 每站停留（终点也留一段，好在那儿读一眼） */
  var raw=travel+names.length*STAGE_DWELL;
  var dur=clamp(raw,STAGE_DUR_MIN,STAGE_DUR_MAX), kk=dur/raw;
  if(kk!==1) for(k=0;k<tms.length;k++) tms[k]*=kk;
  /* 相邻站点的段性质与纯路程耗时（不含停留）：定位「一跳而过」的节点 */
  var hopList=[];
  for(k=1;k<names.length;k++){
    var a0=npos[k-1], b0=npos[k], ci, arr=null;
    for(ci=0;ci<chunks.length;ci++) if(b0>=chunks[ci].i0&&b0<=chunks[ci].i1) arr=chunks[ci];   /* 抵达这一站所走的段 */
    hopList.push({from:names[k-1], to:names[k], kind:(arr&&arr.kind==="warp"?"warp":"walk"),
      d:Math.round(Math.hypot(pts[k].x-pts[k-1].x,pts[k].y-pts[k-1].y)),
      sec:+Math.max(0,tms[b0]-tms[a0]-STAGE_DWELL*kk).toFixed(2)});
  }
  STAGE_HOPS[st.id]=hopList;
  STAGE_SEGS[st.id]=chunks.map(function(c){ return [c.kind,c.i0,c.i1,(c.from||"").split(" · ")[0],(c.to||"").split(" · ")[0],Math.round(c.len),+c.sec.toFixed(2)]; });
  STAGE_NPOS[st.id]=npos;
  STAGE_PATHS[st.id]=path;
  STAGE_WARPS[st.id]=warps;
  STAGE_TIME[st.id]=tms;
  STAGE_TAG[st.id]=tags;
  STAGE_DUR[st.id]=dur;
});
