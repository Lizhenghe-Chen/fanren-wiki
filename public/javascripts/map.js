var touch=null, TOUCH_SLOP=10;  /* 指尖比光标粗：触控命中半径额外放宽 */
function bindTouch(){
  cv.addEventListener('touchstart',function(e){
    if(MODE!=="explore") return;
    e.preventDefault();
    var r=cv.getBoundingClientRect();
    if(e.touches.length===1){
      var t=e.touches[0];
      touch={type:"pan",sx:t.clientX-r.left,sy:t.clientY-r.top,cx:cam.x,cy:cam.y,ts:Date.now()};
    }else if(e.touches.length===2){
      var t1=e.touches[0],t2=e.touches[1];
      touch={type:"pinch",d:Math.hypot(t2.clientX-t1.clientX,t2.clientY-t1.clientY),z:cam.zoom,
        cx:(t1.clientX+t2.clientX)/2-r.left,cy:(t1.clientY+t2.clientY)/2-r.top};
    }
  },{passive:false});
  cv.addEventListener('touchmove',function(e){
    if(MODE!=="explore"||!touch) return;
    e.preventDefault();
    hideTools();
    var r=cv.getBoundingClientRect();
    if(touch.type==="pan"&&e.touches.length===1){
      var t=e.touches[0];
      var mx=t.clientX-r.left, my=t.clientY-r.top;
      cam.x=touch.cx-(mx-touch.sx)/cam.zoom; cam.y=touch.cy-(my-touch.sy)/cam.zoom;
      cam.lx=cam.x; cam.ly=cam.y; cam.tx=cam.x; cam.ty=cam.y;
    }else if(touch.type==="pinch"&&e.touches.length===2){
      var t1=e.touches[0],t2=e.touches[1];
      var d=Math.hypot(t2.clientX-t1.clientX,t2.clientY-t1.clientY);
      if(touch.d>0){
        zoomAt(touch.cx,touch.cy,touch.z*d/touch.d);
      }
    }
  },{passive:false});
  cv.addEventListener('touchend',function(e){
    if(!touch) return;
    var was=touch;
    touch=null;
    if(was.type==="pan"&&Date.now()-was.ts<350){
      var t=e.changedTouches[0], r=cv.getBoundingClientRect();
      var sx=t.clientX-r.left, sy=t.clientY-r.top;
      var loc=hitTest(sx,sy,TOUCH_SLOP);
      if(loc) showDetail(loc); else hideDetail();
    }
  },{passive:false});
}

